// Writes src/data/areas.gen.ts: the ISO 3166-2 code of every area each
// national sheet draws, so `parse` can check an area without loading its
// sheet. `pnpm build:maps` runs it after writing the sheets; a test fails if
// the index and the sheets disagree.
import { writeFileSync } from "node:fs"

import { type Country, countries } from "../src/countries.ts"
import { load, nations } from "../src/sheet.ts"
import { uncoded } from "./build-maps/uncoded.gen.ts"

const prefixes = new Map<Country, string>(countries.map(({ code, alpha2 }) => [code, alpha2]))

// Each national sheet's ISO-coded areas, on the map or in an inset, as the
// index writes them: the codes after the country's prefix, sorted, joined by
// spaces. Countries with none are left out.
export const coded = async (): Promise<Readonly<Partial<Record<Country, string>>>> => {
  const entries = await Promise.all(
    nations.map(async (country) => {
      const sheet = await load(country)
      const kept = new Set(uncoded[country] ?? [])
      const prefix = `${prefixes.get(country)}-`
      const suffixes = [
        ...(sheet.subdivisions?.areas ?? []),
        ...sheet.insets.flatMap((inset) => inset.areas ?? []),
      ]
        .map((area) => area.code)
        .filter((code) => !kept.has(code))
        .map((code) => code.slice(prefix.length))
        .toSorted()

      return suffixes.length === 0 ? [] : [[country, suffixes.join(" ")] as const]
    }),
  )

  return Object.fromEntries(entries.flat())
}

if (import.meta.main) {
  const areas = await coded()
  const source = `// Generated by scripts/areas.ts. Do not edit.
import type { Country } from "../countries.ts"

// The areas each national sheet draws under an ISO 3166-2 code, as the code
// after the country's prefix, separated by spaces: USA's "CA" is US-CA. The
// areas in scripts/build-maps/uncoded.gen.ts keep their source's code and are
// left out.
export const areas: Readonly<Partial<Record<Country, string>>> = ${JSON.stringify(areas)}
`

  writeFileSync(new URL("../src/data/areas.gen.ts", import.meta.url), source)
  console.info(`Wrote src/data/areas.gen.ts: ${Object.keys(areas).length} countries`)
}
