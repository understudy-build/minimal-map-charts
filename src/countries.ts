export type Country = (typeof countries)[number]["code"]

// The one country Intl.DisplayNames cannot name: JG is not an ISO code.
const unnamed: Readonly<Partial<Record<Country, string>>> = { CHI: "Channel Islands" }

// Country names in a locale, from the runtime's own Intl data.
export const names = (locale: string) => {
  const display = new Intl.DisplayNames([locale], { type: "region", fallback: "none" })
  const byCode = new Map<Country, string>(
    countries.map(({ code, alpha2 }) => [code, display.of(alpha2) ?? unnamed[code] ?? code]),
  )

  return (code: Country): string => byCode.get(code) ?? code
}
